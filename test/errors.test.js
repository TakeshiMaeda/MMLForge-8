// MMLのエラーのテスト。
//
// エラー文言は「トラックN 位置M: 内容」という仕様であり、UIにそのまま出る。
// つまり文言と位置は実装の詳細ではなく外向きの約束なので、全文で押さえる。
// 位置は必ず「原文」の文字位置（1始まり）。リピート [ ]n の後ろでも展開後の位置にはならない。
// mml.js の throw 箇所を網羅する（増やしたらここも増やすこと）。
'use strict';
const { loadPlayer, throwsWith, eq, ok } = require('./helper');
const P = loadPlayer();
const parse = (s) => () => P.parse(s);

module.exports = {

  // ── 位置と書式そのもの ──
  '位置は1始まりで、問題の文字を指す'() {
    // "cde%" の % は4文字目
    throwsWith(parse('cde%'), 'トラック1 位置4: 解釈できない文字です: "%"');
  },
  '解釈できない文字はその文字を引用して示す'() {
    throwsWith(parse(';コメント'), 'トラック1 位置1: 解釈できない文字です: ";"',
      'コメントは mml.js の機能ではないのでエラーになる');
  },
  'Error にはトラック番号(0始まり)と位置(1始まり)がプロパティで付く'() {
    let e = null;
    try { P.parse('cde%'); } catch (err) { e = err; }
    ok(e, '例外が投げられる');
    eq(e.track, 0, 'track はトラックのインデックス');
    eq(e.pos, 4, 'pos は文言の「位置M」と同じ値');
  },
  'リピートの後ろでも位置は原文を指す（展開後の位置ではない）'() {
    // "[cde]3 %" の % は8文字目。展開すると "cdecdecde %" で11文字目になってしまうが、それは仕様違反
    throwsWith(parse('[cde]3 %'), 'トラック1 位置8: 解釈できない文字です: "%"');
  },
  'リピートの中のエラーも原文を指す'() {
    throwsWith(parse('[cd]2 [e %]2'), 'トラック1 位置10: 解釈できない文字です: "%"');
  },
  '2周目以降でしか起きないエラーも原文を指す'() {
    // 1周目は o4→o5、2周目で o5→o6 … 4周目に o8 から > で範囲外になる
    throwsWith(parse('[c >]5'), 'トラック1 位置4: > でオクターブが 8 を超えます');
  },

  // ── リピート ──
  '[ ] の対応が取れない（閉じ忘れ）は [ の位置を指す'() {
    throwsWith(parse('c [de'), 'トラック1 位置3: [ に対応する ] がありません');
  },
  '[ ] の対応が取れない（開き忘れ）は ] の位置を指す'() {
    throwsWith(parse('cde]2'), 'トラック1 位置4: ] に対応する [ がありません');
  },
  'ネストの閉じ忘れは内側の [ を指す'() {
    throwsWith(parse('[c [d]2'), 'トラック1 位置1: [ に対応する ] がありません');
  },
  '無限ループの後ろに音符があると拒否する（[ の位置）'() {
    throwsWith(parse('c [de]0 f'),
      'トラック1 位置3: 無限ループ（数字なし・0 の [ ]）はトラックの末尾にのみ書けます（リピートの中も不可）');
  },
  '無限ループをリピートの中に書くと拒否する'() {
    throwsWith(parse('[[cd]0]2',),
      'トラック1 位置2: 無限ループ（数字なし・0 の [ ]）はトラックの末尾にのみ書けます（リピートの中も不可）');
  },
  '無限ループの中身が空だと拒否する'() {
    throwsWith(parse('c4 []'), 'トラック1 位置4: 無限ループの中身には音符か休符が必要です');
  },
  '無限ループの後ろが空白と | だけなら通る'() {
    const r = P.parse('c4 [de]0 |  ');
    eq(r.notes.length, 3, '音符は3つ');
  },
  '] の直後の付点はエラー（最後の周の音符には付かない）'() {
    throwsWith(parse('[c]2. d'), 'トラック1 位置5: 解釈できない文字です: "."');
  },
  '] の直後のシャープはエラー（最後の周の音符には付かない）'() {
    throwsWith(parse('[c]2# d'), 'トラック1 位置5: 解釈できない文字です: "#"');
  },

  // ── 音長 ──
  // 値の範囲エラーは「その値の先頭」を指す（直せばよい場所を指す）。
  // 数値が無いエラーも「数値があるべき場所」を指すので、両者で流儀が揃う
  '音長0は拒否する'() {
    throwsWith(parse('c0'), 'トラック1 位置2: 音長は1以上で指定してください');
  },

  // ── 単独コマンドの引数不足・範囲外（記法表の範囲: o0-8 v0-15 q1-8） ──
  'o に数値が無い'() {
    throwsWith(parse('o'), 'トラック1 位置2: o の後にオクターブ数(0-8)が必要です');
  },
  'o9 は範囲外'() {
    throwsWith(parse('o9 c'), 'トラック1 位置2: o の後にオクターブ数(0-8)が必要です');
  },
  'o8 は通る'() {
    eq(P.parse('o8 c').notes[0].midi, 108);
  },
  '> で o8 を超えると拒否する'() {
    throwsWith(parse('o8 > c'), 'トラック1 位置4: > でオクターブが 8 を超えます');
  },
  '< で o0 を下回ると拒否する'() {
    throwsWith(parse('o0 < c'), 'トラック1 位置4: < でオクターブが 0 を下回ります');
  },
  'l に数値が無い'() {
    throwsWith(parse('l'), 'トラック1 位置2: l の後に音長が必要です');
  },
  'l0 は拒否する'() {
    throwsWith(parse('l0'), 'トラック1 位置2: l の後に音長が必要です');
  },
  't に数値が無い'() {
    throwsWith(parse('t'), 'トラック1 位置2: t の後にテンポが必要です');
  },
  't0 は拒否する'() {
    throwsWith(parse('t0'), 'トラック1 位置2: t の後にテンポが必要です');
  },
  'v に数値が無い'() {
    throwsWith(parse('v'), 'トラック1 位置2: v の後に音量(0-15)が必要です');
  },
  'v16 は範囲外'() {
    throwsWith(parse('v16 c'), 'トラック1 位置2: v の後に音量(0-15)が必要です');
  },
  'q に数値が無い'() {
    throwsWith(parse('q'), 'トラック1 位置2: q の後にゲート(1-8)が必要です');
  },
  'q0 と q9 は範囲外'() {
    throwsWith(parse('q0 c'), 'トラック1 位置2: q の後にゲート(1-8)が必要です');
    throwsWith(parse('q9 c'), 'トラック1 位置2: q の後にゲート(1-8)が必要です');
  },
  'p に数値が無い'() {
    throwsWith(parse('p c4'), 'トラック1 位置2: p の後にポルタメント時間(ミリ秒)が必要です');
  },

  // ── 音色・エンベロープ ──
  '@ に音色番号が無い'() {
    throwsWith(parse('@ c4'), 'トラック1 位置2: @ の後に音色番号(0-4)が必要です');
  },
  '範囲外の音色番号'() {
    throwsWith(parse('@5 c4'), 'トラック1 位置2: @ の後に音色番号(0-4)が必要です');
  },
  '@e の値が足りない（カンマが来ない）'() {
    throwsWith(parse('@e3,0,100 c4'), 'トラック1 位置11: @e の値はカンマ区切りで指定してください');
  },
  '@e のカンマの後に値が無い'() {
    throwsWith(parse('@e3,0,100, c4'), 'トラック1 位置12: @e は attack,decay,sustain,release の4値が必要です');
  },
  '@e の区切りがカンマでない'() {
    throwsWith(parse('@e3 0 100 40'), 'トラック1 位置5: @e の値はカンマ区切りで指定してください');
  },
  '@e の sustain は % なので 100 を超えると拒否する'() {
    // 位置7 = 101 の先頭（3つ目の値そのものを指す）
    throwsWith(parse('@e3,0,101,40 c'), 'トラック1 位置7: @e の sustain は 0-100 で指定してください');
  },
  '@e の値の前に空白があっても、指すのは値の先頭'() {
    throwsWith(parse('@e3, 0, 101, 40 c'), 'トラック1 位置9: @e の sustain は 0-100 で指定してください');
  },

  // ── & タイ/スラー ──
  '& の前に音符が無い'() {
    throwsWith(parse('&c4'), 'トラック1 位置1: & の前に音符が必要です');
  },
  '& の後が休符'() {
    throwsWith(parse('c4&r4'), 'トラック1 位置4: & の後には音符が必要です（休符は繋げません）');
  },
  '& でトラックが終わる（& の位置を指す）'() {
    throwsWith(parse('c4&'), 'トラック1 位置3: & の後には音符が必要です');
  },
  '& の後にコマンドだけ続いて音符が無い'() {
    throwsWith(parse('c4& o5 v10'), 'トラック1 位置3: & の後には音符が必要です');
  },

  // ── m LFO ──
  'm の値が足りない（カンマが来ない）'() {
    throwsWith(parse('m120,5 c4'), 'トラック1 位置8: m の値はカンマ区切りで指定してください');
  },
  'm のカンマの後に値が無い'() {
    throwsWith(parse('m120,5, c4'), 'トラック1 位置9: m は 遅れ,速さ,深さ の3値が必要です');
  },

  // ── @b ベンド ──
  '@b の値が足りない（カンマが来ない）'() {
    throwsWith(parse('@b-200 c4'), 'トラック1 位置8: @b の値はカンマ区切りで指定してください');
  },
  '@b のカンマの後に値が無い'() {
    throwsWith(parse('@b-200, c4'), 'トラック1 位置9: @b は ずれ(セント),時間(ミリ秒) の2値が必要です');
  },

  // ── リピートの上限（タイプミス1つでブラウザが固まらないように） ──
  'リピートの展開が大きすぎると拒否する（音符と休符の合計。位置は一番外の [）'() {
    // 1音あたり約570B なので 100万で約0.6GB。ここを超えたら止める
    throwsWith(parse('c [[r]1000]1001'),
      'トラック1 位置3: リピートの展開が大きすぎます（音符と休符の合計が 1000000 を超えました）');
  },
  '上限ちょうどまでは通る'() {
    eq(P.parse('[[r]1000]1000').notes.length, 0);
  },

  // ── トラック番号 ──
  'トラック番号は1始まりで、エラーの起きたトラックを指す'() {
    // parse() は単トラック用なので常にトラック1。複数トラックは play() 側の責務
    throwsWith(parse('%'), 'トラック1 位置1:');
  },

  // ── play() 固有（パースは再生の前に済むので AudioContext 無しで確かめられる） ──
  '空のトラックしか無ければ play() は拒否する'() {
    throwsWith(() => P.play(''), '演奏する音符がありません');
    throwsWith(() => P.play([]), '演奏する音符がありません');
    throwsWith(() => P.play(['', ' | ']), '演奏する音符がありません');
  },
  'play() のエラーは何トラック目かを示す'() {
    throwsWith(() => P.play(['cde', 'c %']), 'トラック2 位置3: 解釈できない文字です: "%"');
  },
};
